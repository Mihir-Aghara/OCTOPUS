import React, { useState, useRef, useEffect } from 'react';
import { KeyRound, Lock, ArrowRight } from 'lucide-react';
import { audioEngine } from '../services/audioEngine';

export default function RetrievePanel({ onRetrieve, showToast, initialCode = '' }) {
  const [digits, setDigits] = useState(['', '', '', '', '', '']);
  const [passcode, setPasscode] = useState('');
  const [needsPasscode, setNeedsPasscode] = useState(false);
  const [loading, setLoading] = useState(false);
  const inputsRef = useRef([]);

  useEffect(() => {
    if (initialCode && initialCode.length === 6) {
      const arr = initialCode.split('');
      setDigits(arr);
      handleRetrieve(initialCode);
    }
  }, [initialCode]);

  const handleChange = (index, value) => {
    const char = value.slice(-1);
    if (!/^\d*$/.test(char)) return;

    const newDigits = [...digits];
    newDigits[index] = char;
    setDigits(newDigits);

    if (char && index < 5) {
      inputsRef.current[index + 1]?.focus();
    }

    if (newDigits.every((d) => d !== '')) {
      const code = newDigits.join('');
      handleRetrieve(code);
    }
  };

  const handleKeyDown = (index, e) => {
    if (e.key === 'Backspace') {
      if (!digits[index] && index > 0) {
        inputsRef.current[index - 1]?.focus();
      } else {
        const newDigits = [...digits];
        newDigits[index] = '';
        setDigits(newDigits);
      }
    } else if (e.key === 'ArrowLeft' && index > 0) {
      inputsRef.current[index - 1]?.focus();
    } else if (e.key === 'ArrowRight' && index < 5) {
      inputsRef.current[index + 1]?.focus();
    } else if (e.key === 'Enter') {
      handleRetrieve();
    }
  };

  const handlePaste = (e) => {
    e.preventDefault();
    const pasted = e.clipboardData.getData('text').replace(/\D/g, '').slice(0, 6);
    if (pasted) {
      const arr = pasted.split('');
      while (arr.length < 6) arr.push('');
      setDigits(arr);
      audioEngine.play('click');

      if (pasted.length === 6) {
        inputsRef.current[5]?.focus();
        handleRetrieve(pasted);
      }
    }
  };

  const handleRetrieve = async (codeOverride) => {
    const code = codeOverride || digits.join('');
    if (code.length !== 6) {
      audioEngine.play('error');
      showToast('Please enter a full 6-digit PIN code.', 'error');
      return;
    }

    setLoading(true);
    try {
      const res = await onRetrieve(code, passcode);
      if (res && res.requiresPasscode) {
        setNeedsPasscode(true);
        audioEngine.play('click');
        showToast('This clip is encrypted with a passcode.', 'info');
      } else {
        audioEngine.play('retrieve');
        showToast('Clip retrieved successfully!', 'success');
      }
    } catch (err) {
      audioEngine.play('error');
      showToast(err.message || 'Failed to retrieve clip.', 'error');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="glass-panel rounded-3xl p-6 sm:p-10 shadow-stripe border border-slate-200/80 text-center max-w-2xl mx-auto bg-white/90 relative overflow-hidden">
      
      {/* Ambient Mesh Glow */}
      <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-96 h-96 bg-indigo-500/10 rounded-full blur-3xl pointer-events-none" />

      <div className="w-16 h-16 rounded-2xl bg-indigo-50 border border-indigo-100 flex items-center justify-center mx-auto mb-4 text-indigo-600 shadow-sm">
        <KeyRound className="w-8 h-8" />
      </div>

      <h2 className="text-2xl font-black text-slate-900 tracking-tight">
        Retrieve Clipboard Content
      </h2>
      <p className="text-xs sm:text-sm text-slate-500 mt-1 max-w-md mx-auto">
        Enter the 6-digit PIN code generated by the sender to view or copy the content instantly.
      </p>

      {/* 6-Digit PIN Box Grid */}
      <div className="flex justify-center items-center gap-1.5 sm:gap-3 my-8" onPaste={handlePaste}>
        {digits.map((digit, idx) => (
          <React.Fragment key={idx}>
            <input
              ref={(el) => (inputsRef.current[idx] = el)}
              type="text"
              inputMode="numeric"
              maxLength={1}
              value={digit}
              onChange={(e) => handleChange(idx, e.target.value)}
              onKeyDown={(e) => handleKeyDown(idx, e)}
              className="w-11 h-14 sm:w-16 sm:h-18 text-center text-xl sm:text-3xl font-mono font-black rounded-2xl glass-input text-slate-900 border border-slate-300 focus:border-indigo-600 focus:ring-4 focus:ring-indigo-500/10 transition-all shadow-sm"
            />
            {idx === 2 && <span className="text-slate-400 font-bold text-lg sm:text-xl">-</span>}
          </React.Fragment>
        ))}
      </div>

      {/* Encrypted Passcode Input if clip is passcode protected */}
      {needsPasscode && (
        <div className="mb-6 max-w-sm mx-auto p-4 rounded-2xl bg-indigo-50 border border-indigo-200 space-y-2 animate-fade-in">
          <div className="flex items-center justify-center gap-2 text-xs font-bold text-indigo-700">
            <Lock className="w-4 h-4" /> Enter Decryption Passcode
          </div>
          <input
            type="password"
            placeholder="Enter secret passcode..."
            value={passcode}
            onChange={(e) => setPasscode(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && handleRetrieve()}
            className="w-full px-4 py-2 rounded-xl glass-input text-xs text-slate-900 text-center"
          />
        </div>
      )}

      {/* Action Button */}
      <button
        onClick={() => handleRetrieve()}
        disabled={loading}
        className="w-full max-w-sm mx-auto py-4 rounded-2xl font-black text-xs uppercase tracking-wider text-white bg-gradient-to-r from-indigo-600 via-purple-600 to-indigo-600 hover:opacity-95 shadow-lg shadow-indigo-200 transition-all active:scale-[0.99] flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
      >
        {loading ? (
          <div className="w-5 h-5 border-2 border-white border-t-transparent rounded-full animate-spin" />
        ) : (
          <>
            <span>Retrieve Clip Now</span>
            <ArrowRight className="w-4 h-4" />
          </>
        )}
      </button>

      <p className="text-xs text-slate-400 mt-4 font-medium">
        💡 Tip: You can paste the 6-digit PIN directly or click share links.
      </p>

    </div>
  );
}
